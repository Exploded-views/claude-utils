#!/bin/sh
# gen-reference.sh [OUT]: regenerate docs/reference.md from claude-memsync's own help output.
#
# Builds cmd/claude-memsync (or uses $MEMSYNC_BIN), runs every subcommand's -h
# (or its no-argument usage, for commands that dispatch to actions) in a
# throwaway HOME, and writes the output under one heading per command, in a
# fixed order. Commands that act without parsing flags (start, stop,
# uninstall, status, version) are never run; they are listed from the
# top-level help only.
#
# CI runs this and fails when the committed file differs:
#   sh scripts/gen-reference.sh && git diff --exit-code docs/reference.md
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
out=${1:-$root/docs/reference.md}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT INT TERM

if [ -n "${MEMSYNC_BIN:-}" ]; then
  bin=$MEMSYNC_BIN
else
  (cd "$root" && go build -o "$tmp/claude-memsync" ./cmd/claude-memsync)
  bin=$tmp/claude-memsync
fi

# A throwaway HOME with a stub config, so commands that load a config before
# parsing their flags (host ...) reach their flag parser. Nothing here touches
# the network: -h returns before any work.
home=$tmp/home
mkdir -p "$home/.claudesync" "$home/.config"
cat > "$home/.claudesync/config.json" <<EOF
{"remoteUrl": "git@github.com:example-org/mem-example.git", "syncDir": "$home/.claudesync"}
EOF

help() {
  # Run one command with a clean environment; normalise the temp path.
  env -i PATH="$PATH" HOME="$home" XDG_CONFIG_HOME="$home/.config" LANG=C \
    "$bin" "$@" </dev/null 2>&1 | sed "s#$tmp#<tmp>#g" || true
}

section() {
  # section "<heading>" args...
  heading=$1
  shift
  printf '\n## `claude-memsync %s`\n\n```text\n' "$heading"
  help "$@"
  printf '```\n'
}

{
  printf '# claude-memsync command reference\n\n'
  printf '<!-- GENERATED by scripts/gen-reference.sh from the binary'"'"'s --help output. Do not edit by hand; CI fails when this file is stale. -->\n\n'
  printf 'Every section is the verbatim output of the command shown. For what the commands do and when to use them, see [setup.md](setup.md), [security.md](security.md) and [claude-memsync.md](claude-memsync.md).\n'

  printf '\n## `claude-memsync --help`\n\n```text\n'
  help --help
  printf '```\n'

  section "init -h" init -h
  section "doctor -h" doctor -h
  section "app" app
  section "app register -h" app register -h
  section "app key-fingerprint -h" app key-fingerprint -h
  section "app-token -h" app-token -h
  section "repo" repo
  section "repo create -h" repo create -h
  section "run -h" run -h
  section "distill -h" distill -h
  section "archive" archive
  section "archive list -h" archive list -h
  section "route" route
  section "route home -h" route home -h
  section "route publish -h" route publish -h
  section "route inherit -h" route inherit -h
  section "changes -h" changes -h
  section "relate -h" relate -h
  section "unrelate -h" unrelate -h
  section "related -h" related -h
  section "related sync -h" related sync -h
  section "related context -h" related context -h
  section "related accept -h" related accept -h
  section "related suggest -h" related suggest -h
  section "related dismiss -h" related dismiss -h
  section "recipients" recipients
  section "join" join
  section "join request -h" join request -h
  section "host" host
  section "host list -h" host list -h
  section "host check-key -h" host check-key -h
  section "host retire -h" host retire -h
  section "install -h" install -h

  printf '\n## Commands without flags\n\n'
  printf '`uninstall`, `start`, `stop`, `status` and `version` take no flags and act when run, so the generator does not run them; their one-line summaries are in the `--help` output above.\n'
} > "$out.tmp"
mv "$out.tmp" "$out"
